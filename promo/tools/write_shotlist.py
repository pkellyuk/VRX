"""Write promo/SHOTLIST.md from the shot list the film is actually built from.

Keeping the document generated means it cannot drift from the film: change a
shot's assets or its caption in vrx_shotlist.py and the document follows.
"""
from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

PROMO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROMO))

from film.vrx_shotlist import FPS, SHOTS, TOTAL_SECONDS, schedule  # noqa: E402

OUT = PROMO / "SHOTLIST.md"


def main() -> int:
    sched = {k: (a, b) for k, a, b in schedule()}
    lines = [
        "# VRX promo - shot list",
        "",
        "Generated by `tools/write_shotlist.py` from `film/vrx_shotlist.py`, which "
        "is the same data the renderer reads. Editing the film means editing that "
        "file and regenerating this one.",
        "",
        f"- Total length: **{TOTAL_SECONDS:.1f} s** ({int(TOTAL_SECONDS * FPS)} "
        f"frames at {FPS} fps)",
        "- Deliverables: `VRX-promo-1080p.mp4` (16:9), "
        "`VRX-promo-vertical-1080x1920.mp4` (9:16), `VRX-promo-poster.png`",
        "- Every picture is a genuine VRX asset. Every claim on screen is one the "
        "repository already makes, named in the Source column below.",
        "",
        "| # | Shot | In | Out | Shows | Assets |",
        "|---|------|----|-----|-------|--------|",
    ]
    for i, shot in enumerate(SHOTS, start=1):
        a, b = sched[shot.key]
        assets = "<br>".join(f"`{x}`" for x in shot.assets)
        lines.append(f"| {i} | **{shot.title}** | {a:.1f} s | {b:.1f} s | "
                     f"{shot.shows} | {assets} |")

    for i, shot in enumerate(SHOTS, start=1):
        a, b = sched[shot.key]
        lines += [
            "",
            f"## {i}. {shot.title} - {a:.1f} s to {b:.1f} s ({shot.seconds:.1f} s)",
            "",
            f"**On screen:** {' / '.join(repr(c) for c in shot.caption)}",
            "",
            f"**Shows:** {shot.shows}",
            "",
            f"**Source:** {shot.source}",
            "",
            f"**Assets:** {', '.join('`' + x + '`' for x in shot.assets)}",
        ]
        if shot.notes:
            lines += ["", f"**Directing notes:** {shot.notes}"]

    lines += [
        "",
        "---",
        "",
        "## How the depth-parallax shots are made",
        "",
        "The three Window shots are not a camera move over a flat picture. Each "
        "frame is the real capture repositioned by the real depth map the app "
        "produced for it:",
        "",
        "1. `film/vrx_dibr.py` loads the capture and its depth map (published in",
        "   `promo/assets/`), crops both to 16:9 with the same transform, and turns",
        "   the depth into a camera-space distance.",
        "2. A virtual camera is moved by `(tx, ty, tz)`. Every output pixel solves",
        "   backwards for the source pixel that projects onto it, by fixed-point",
        "   iteration, so the parallax is sub-pixel and the near field moves further",
        "   than the far field - the same thing a stereo pair would do.",
        "3. The dolly towards the screen (`tz > 0`) is not decoration: it is what",
        "   keeps every sample inside the capture, so the frame edges are never left",
        "   without a source. Only the thin slivers revealed behind near objects need",
        "   filling, and those are inpainted.",
        "",
        "`tools/analyse_depth.py` measured the depth convention rather than assuming",
        "it (the brightest depth sits on the bottom rows and the darkest in the upper",
        "middle, for all three published pairs), and `tools/test_dibr.py` checks the",
        "renderer is an exact identity at zero camera movement.",
        "",
        f"_Generated {date.today().isoformat()}._",
        "",
    ]

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(lines)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
